    H = 32
    sheet = Image.new("RGBA", (2000, H * S), (64, 58, 66, 255))
    x = 0
    for group in (imgs, refs):
        for im in group:
            sheet.alpha_composite(im.resize((im.width * S, im.height * S), Image.NEAREST), (x, (H - im.height) * S))
            x += (im.width + 3) * S
        x += 8 * S
    sheet.crop((0, 0, x, H * S)).save(OUT / "_review_hand.png")
