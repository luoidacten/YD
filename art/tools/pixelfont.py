# marks: (rows, anchor) drawn above the glyph top (or below the baseline for dot below)
MARK = {
    "́": ["..#", ".#."],          # acute
    "̀": ["#..", ".#."],          # grave
    "̉": [".##", "..#", ".#."],   # hook above
    "̃": [".#.#", "#.#."],        # tilde
    "̂": [".#.", "#.#"],          # circumflex
    "̆": ["#.#", ".#."],          # breve
}
DOT_BELOW = "̣"
HORN = "̛"


def _glyph_rows(ch):
    return G.get(ch) or G.get(ch.upper()) or G["?"]


def _compose(ch):
    """Return (base rows, list of above-marks, dot_below, horn)."""
    if ch in G:
        return G[ch], [], False, False
    d = unicodedata.normalize("NFD", ch)
    base, marks = d[0], d[1:]
    rows = list(_glyph_rows(base))
    above = [m for m in marks if m in MARK]
    return rows, above, DOT_BELOW in marks, HORN in marks


def glyph(ch):
    """Return (width, list of (x, y) pixels) in a cell of height H; y=0 is the top of the accent area.
    Marks stack vertically: 1 empty row above the letter, then circumflex/breve, then the tone mark."""
    rows, above, dot, horn = _compose(ch)
    w = max(len(r) for r in rows)
    px = [(x, ASC + y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"]
    top = min((y for _, y in px), default=ASC)
    if horn:
        px += [(w, top), (w, top - 1)]
    stack = top - 2  # bottom row available for the first mark
    for m in sorted(above, key=lambda m: 0 if m in ("̂", "̆") else 1):
        mr = MARK[m]
        mw = len(mr[0])
        ox = (w - mw + 1) // 2
        oy = stack - len(mr) + 1
        px += [(ox + x, oy + y) for y, r in enumerate(mr) for x, c in enumerate(r) if c == "#"]
        stack = oy - 1 if m in ("̂", "̆") else oy - 1
        if m in ("̂", "̆"):
            stack = oy  # tone mark sits directly on the circumflex/breve (no gap)
            stack -= 1
    if dot:
        px.append((w // 2, ASC + CAP))
    return w + (1 if horn else 0), px


def text_size(s, scale=1, spacing=1):
    w = sum(glyph(c)[0] + spacing for c in s) - spacing if s else 0
    return w * scale, H * scale


def draw_text(img, x, y, s, color, scale=1, spacing=1, shadow=None):
    """Draw text with its accent area starting at y. shadow: color drawn 1px down-right (scaled)."""
    px = img.load()
    W, Hh = img.size

    def put(gx, gy, col):
        for dy in range(scale):
            for dx in range(scale):
                X, Y = gx + dx, gy + dy
                if 0 <= X < W and 0 <= Y < Hh:
                    px[X, Y] = col
    cx = x
    for ch in s:
        w, pts = glyph(ch)
        for gx, gy in pts:
            if shadow:
                put(cx + gx * scale + scale, y + gy * scale + scale, shadow)
        for gx, gy in pts:
            put(cx + gx * scale, y + gy * scale, color)
        cx += (w + spacing) * scale
    return cx


