def build(name, art):
    rows = art.strip("\n").split("\n")
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w + 2, len(rows) + 2), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in C:
                h = C[ch]
                px[x + 1, y + 1] = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)
    img = pixelize.outline(img)
    OUT.mkdir(parents=True, exist_ok=True)
    img.save(OUT / f"weapon_{name}.png")
    return img


if __name__ == "__main__":
    S = 5
    imgs = [build(n, a) for n, a in W.items()]
    H = 30
    sheet = Image.new("RGBA", (3000, H * S), (64, 58, 66, 255))
    x = 0
    for im in imgs:
        sheet.alpha_composite(im.resize((im.width * S, im.height * S), Image.NEAREST), (x, (H - im.height) * S))
        x += (im.width + 2) * S
    sheet.crop((0, 0, x, H * S)).save(OUT / "_review_batch2.png")
    print(len(imgs), "weapons")
